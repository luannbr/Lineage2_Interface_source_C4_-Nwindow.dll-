// _wchartodigit (0x100c0ebe): the value of a decimal digit of any script it knows, -1 for
// anything else. ASCII, fullwidth and these zeros (the UCRT's internal
// wide_character_to_digit has the same ranges, but it is not exported)
inline INT NWcharToDigit(TCHAR C)
{
    static const TCHAR Zeros[] = {0x0660, 0x06F0, 0x0966, 0x09E6, 0x0A66, 0x0AE6, 0x0B66, 0x0C66,
                                  0x0CE6, 0x0D66, 0x0E50, 0x0ED0, 0x0F20, 0x1040, 0x17E0, 0x1810};
    if (C < 0x30)
        return -1;
    if (C < 0x3A)
        return C - 0x30;
    if (C >= 0xFF10)
        return C < 0xFF1A ? C - 0xFF10 : -1;
    for (INT i = 0; i < (INT)ARRAYSIZE(Zeros); i++)
    {
        if (C < Zeros[i])
            return -1;
        if (C < Zeros[i] + 10)
            return C - Zeros[i];
    }
    return -1;
}

// _wtol (0x100bdca1): spaces, one sign, then digits added up with no overflow check -
// "2147483648" gives -2147483648 and "9999999999" 1410065407, where the UCRT's _wtol
// saturates at 2147483647
inline INT NWtol(const TCHAR* Str)
{
    while (NIswctype(*Str, _SPACE))
        Str++;
    TCHAR C = *Str++;
    const TCHAR Sign = C;
    if (C == '-' || C == '+')
        C = *Str++;
    DWORD Total = 0;
    for (INT Digit; (Digit = NWcharToDigit(C)) != -1; C = *Str++)
        Total = Total * 10 + Digit;
    return (INT)(Sign == '-' ? 0 - Total : Total);
}

// atol (0x100be1b7): the same for a narrow string ("C" locale spaces, ASCII digits; the narrow
// tables of the two CRTs agree)
inline INT NAtol(const CHAR* Str)
{
    while (isspace((BYTE)*Str))
        Str++;
    INT C = (BYTE)*Str++;
    const INT Sign = C;
    if (C == '-' || C == '+')
        C = (BYTE)*Str++;
    DWORD Total = 0;
    for (; C >= '0' && C <= '9'; C = (BYTE)*Str++)
        Total = Total * 10 + (C - '0');
    return (INT)(Sign == '-' ? 0 - Total : Total);
}
