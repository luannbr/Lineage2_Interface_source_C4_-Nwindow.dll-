#!/usr/bin/env python3
"""The 7 color cursors of the stock NWindow.dll (the C2 image has the same 7 as the C1 one: the groups
below, Korean, 32x32 8-bit; checked on orig/NWindow.dll, 03/03/2005 build), for the resources of the standalone build
(docs/notas/Standalone.md, section 8). Run by the build (CMakeLists.txt): orig/ is not in git,
so neither are the cursors.

The stock images have RT_GROUP_CURSOR 101, 102, 106, 107, 127, 130 and 131 (Korean, 1042), one
32x32 8-bit image each, RT_CURSOR 1..7. NCVirtualWndMain::LoadCursors loads them by group id
with GNWindowInstance. Each one becomes a .cur file; the .rc written next to them lists them
in the order of their RT_CURSOR ids, which is the order rc numbers them in, so the compiled
resources get the stock ids back.

  python tools/extract_cursors.py OUT_DIR     writes OUT_DIR/cursor<group>.cur and
                                              OUT_DIR/NWindowCursors.rc
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]
ORIG = ROOT / "orig" / "NWindow.dll"
RT_CURSOR, RT_GROUP_CURSOR = 1, 12
LANG_KOREAN = 1042


def resources(pe: pefile.PE, rtype: int) -> dict[int, tuple[int, bytes]]:
    """{id: (language, data)} of one resource type."""
    out = {}
    for t in pe.DIRECTORY_ENTRY_RESOURCE.entries:
        if t.id != rtype:
            continue
        for e in t.directory.entries:
            for lang in e.directory.entries:
                d = lang.data.struct
                out[e.id] = (lang.id, pe.get_data(d.OffsetToData, d.Size))
    return out


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    pe = pefile.PE(str(ORIG))
    images = resources(pe, RT_CURSOR)
    groups = resources(pe, RT_GROUP_CURSOR)
    entries = []  # (cursor id, group id, file)
    for gid, (lang, data) in sorted(groups.items()):
        if lang != LANG_KOREAN:
            raise SystemExit(f"group cursor {gid}: language {lang}")
        reserved, rtype, count = struct.unpack_from("<HHH", data)
        if rtype != 2 or count != 1:
            raise SystemExit(f"group cursor {gid}: type {rtype}, {count} images")
        width, height2, planes, bits, size, cid = struct.unpack_from("<HHHHIH", data, 6)
        clang, image = images[cid]
        if clang != LANG_KOREAN or len(image) != size:
            raise SystemExit(f"cursor {cid}: language {clang}, {len(image)} bytes")
        hot_x, hot_y = struct.unpack_from("<HH", image)
        dib = image[4:]
        # .cur: ICONDIR (type 2 = cursor) + one ICONDIRENTRY (height not doubled, the hotspot
        # where an icon has planes/bit count) + the DIB
        cur = struct.pack("<HHH", 0, 2, 1)
        cur += struct.pack("<BBBBHHII", width & 0xFF, (height2 // 2) & 0xFF, 0, 0, hot_x, hot_y,
                           len(dib), 6 + 16)
        cur += dib
        path = out / f"cursor{gid}.cur"
        path.write_bytes(cur)
        entries.append((cid, gid, path))
    if sorted(c for c, _, _ in entries) != sorted(images):
        raise SystemExit("RT_CURSOR images outside the groups")
    lines = [
        "// Generated by tools/extract_cursors.py from orig/NWindow.dll - not in git.",
        "// The color cursors, in the order of their stock RT_CURSOR ids (rc numbers them 1, 2...).",
        "LANGUAGE 0x12, 0x01  // Korean (1042), as in the stock image",
    ]
    for cid, gid, path in sorted(entries):
        lines.append(f'{gid} CURSOR "{path.resolve().as_posix()}"  // RT_CURSOR {cid}')
    rc = out / "NWindowCursors.rc"
    rc.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"{len(entries)} cursors -> {rc}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
