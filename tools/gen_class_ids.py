#!/usr/bin/env python3
"""include/nwindow/NClasses.gen.h: the UClass of every native class, for code that needs a
class not declared yet (IsA tests, construction). Hook-mode scaffolding like nw::StockCall:
once a class is declared, code uses Class::StaticClass() instead.

Hook mode: the stock UClass (its address in the stock image). Standalone: our own, through
the autoclass<Class> variable IMPLEMENT_CLASS defines (src/standalone/Classes.gen.cpp).
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    classes = sorted(json.loads((ROOT / "analysis/classes.json").read_text(encoding="utf-8")),
                     key=lambda c: c["cpp"].lower())
    lines = [
        "// Generated by tools/gen_class_ids.py from analysis/classes.json - do not edit.",
        "// NClass::X() = the UClass of native class X: the stock one in hook mode, ours",
        "// (autoclassX, IMPLEMENT_CLASS) in the standalone build.",
        "#pragma once",
        "",
        "class UClass;",
        "",
        "#if NW_HOOK_MODE",
        '#include "re/NwHook.h"',
        "",
        "namespace NClass {",
    ]
    for c in classes:
        lines.append(f"inline UClass* {c['cpp']}() {{ return (UClass*)::nw::Addr(0x{c['static_class']:08x}); }}"
                     f"  // sizeof 0x{c['size']:X}, super {c['super']}")
    lines += ["}  // namespace NClass", "", "#else", ""]
    for c in classes:
        lines.append(f'extern "C" UClass* autoclass{c["cpp"]};')
    lines += ["", "namespace NClass {"]
    for c in classes:
        lines.append(f"inline UClass* {c['cpp']}() {{ return autoclass{c['cpp']}; }}")
    lines += ["}  // namespace NClass", "", "#endif", ""]
    out = ROOT / "include" / "nwindow" / "NClasses.gen.h"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(classes)} classes -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
