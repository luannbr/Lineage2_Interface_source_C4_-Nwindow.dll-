#!/usr/bin/env python3
"""src/re/Prologues.gen.cpp: what the hook installer must know about every hookable stock function.

For each game/init function of db/functions.csv:
  room   bytes that can be overwritten at the entry (first body range + int3/nop padding after it);
         a hook needs 5 (jmp rel32);
  steal  length of the whole instructions covering the first 5 bytes: copied into the trampoline
         that keeps the stock code callable;
  flags  PF_REL32   stolen bytes hold a call/jmp rel32 (the trampoline re-targets it)
         PF_NOTRAMP stolen bytes hold a rel8 branch, or the function branches back into them
         PF_ENDS    the function returns inside the stolen bytes (trampoline = copy, no jmp back)
  expect the first 8 stock bytes, relmask marks the ones covered by a relocation (they change
         when the image is rebased and are not compared).
The stock image never changes, so the generated file is committed.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from nwd.image import ROOT, Image  # noqa: E402

PF_REL32, PF_NOTRAMP, PF_ENDS = 1, 2, 4


def main() -> int:
    img = Image()
    ghidra = {int(r["va"], 16): r for r in csv.DictReader(
        (ROOT / "analysis/ghidra/functions.tsv").open(encoding="utf-8"), delimiter="\t")}
    # entries Ghidra missed (db/extra_functions.csv): one range, from their size
    extra = (ROOT / "db/extra_functions.csv").open(encoding="utf-8")
    for r in csv.DictReader(l for l in extra if not l.startswith("#")):
        va = int(r["va"], 16)
        ghidra.setdefault(va, {"ranges": f"{va:x}-{va + int(r['size']) - 1:x}"})
    entries = sorted(ghidra)
    db = [r for r in csv.DictReader((ROOT / "db/functions.csv").open(encoding="utf-8"))
          if r["kind"] in ("game", "init")]

    out = []
    for r in db:
        va = int(r["va"], 16)
        g = ghidra[va]
        ranges = [tuple(int(x, 16) for x in rg.split("-")) for rg in g["ranges"].split(",")]
        first_end = next(b for a, b in ranges if a == va)
        room = first_end - va + 1
        p = first_end + 1
        while img.in_text(p) and img.read(p, 1)[0] in (0xCC, 0x90) and p not in ghidra:
            room += 1
            p += 1

        steal, flags, relat = 0, 0, 0xFF
        for ins in img.disasm(va, 32, stop_at_ret=False, limit=8):
            b0 = ins.bytes[0]
            is_rel32 = (b0 in (0xE8, 0xE9) and ins.size == 5) or \
                       (b0 == 0x0F and ins.size == 6 and 0x80 <= ins.bytes[1] <= 0x8F)
            if is_rel32:
                if relat != 0xFF:
                    flags |= PF_NOTRAMP  # only one rel32 is re-targeted
                flags |= PF_REL32
                relat = steal
            elif b0 == 0xEB or 0x70 <= b0 <= 0x7F or b0 in (0xE0, 0xE1, 0xE2, 0xE3):
                flags |= PF_NOTRAMP
            steal += ins.size
            if ins.mnemonic in ("ret", "retn") or (ins.mnemonic == "jmp" and not ins.op_str.startswith("0x")):
                if steal < 5:
                    flags |= PF_ENDS
                break
            if steal >= 5:
                break
        if steal < 5 and not flags & PF_ENDS:
            flags |= PF_NOTRAMP

        # branches back into the stolen bytes make the trampoline unsafe
        for a, b in ranges:
            for ins in img.disasm(a, b - a + 1, stop_at_ret=False, limit=100000):
                if ins.address > b:
                    break
                if ins.mnemonic.startswith("j") and ins.op_str.startswith("0x"):
                    t = int(ins.op_str, 16)
                    if va < t < va + steal:
                        flags |= PF_NOTRAMP

        expect = img.read(va, 8)
        relmask = 0
        for k in range(8):
            for rr in range(va + k - 3, va + k + 1):
                if rr in img.reloc_set:
                    relmask |= 1 << k
        out.append((va, steal, min(room, 0xFFFF), flags, relat, expect, relmask, r["name"]))

    lines = [
        "// Generated by tools/gen_prologues.py from orig/NWindow.dll - do not edit.",
        '#include "re/NwPrologue.h"',
        "",
        "namespace nw {",
        "",
        "const Prologue kPrologues[] = {",
    ]
    for va, steal, room, flags, relat, expect, relmask, name in out:
        eb = ", ".join(f"0x{x:02x}" for x in expect)
        lines.append(f"    {{0x{va:08x}, {steal}, {room}, 0x{flags:x}, 0x{relat:02x}, 0x{relmask:02x}, "
                     f"{{{eb}}}}},  // {name}")
    lines += ["};", "", f"const unsigned kPrologueCount = {len(out)};", "", "}  // namespace nw", ""]
    (ROOT / "src/re/Prologues.gen.cpp").write_text("\n".join(lines), encoding="utf-8")
    n_small = sum(1 for o in out if o[2] < 5)
    n_notramp = sum(1 for o in out if o[3] & PF_NOTRAMP)
    if len({o[0] for o in out}) != len(out):
        raise SystemExit("duplicate function entries in db/functions.csv")
    print(f"{len(out)} prologues; {n_small} too small to hook; {n_notramp} without trampoline")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
